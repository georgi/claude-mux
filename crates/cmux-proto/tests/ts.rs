//! Writes the TypeScript wire types to `web/src/api/types.ts`.
//!
//! Every type that crosses the wire is listed once below, in a fixed order, so
//! the file is the same on every run. Large integers (`u64`, `Timestamp`)
//! become `number`: JSON carries them as plain numbers.

use std::path::Path;

use cmux_core::ids::AgentPath;
use cmux_core::model::QueuedSpawn;
use cmux_proto::api::*;
use cmux_proto::stream::*;
use cmux_proto::view::*;
use ts_rs::{Config, TS};

const HEADER: &str = "// Generated by cmux-proto (cargo test -p cmux-proto). Do not edit.\n";

macro_rules! decls {
    ($cfg:expr; $($t:ty),* $(,)?) => {
        vec![$(<$t as TS>::decl($cfg)),*]
    };
}

fn generate() -> String {
    let cfg = Config::new().with_large_int("number");
    let decls = decls![&cfg;
        // Ids
        PlanId, TaskId, AgentPath, AgentId, TermId, ItemId, ClientId,
        // Core state
        PlanState, TaskState, Repo, Limits, QueuedSpawn, Criterion, Note, PrRef, CiMark,
        Level, Life, Activity, Report, ReportStatus, TokenUsage, TermKind,
        Recipient, ItemKind, Delivery, DeliveryPath,
        // Views
        StateView, PlanView, TaskView, TaskDetail, AgentView, TerminalView, ItemView,
        ChatEntry, ChatRole, ChatKind, ChatTool, DeltaView, ChangeView, ObjectRef,
        // REST
        ErrorCode, ErrorBody, Scope, ServerInfo, StatusResp, AgentStatus, Created,
        CreatePlanReq, RepoSpec, PlanBody, CreateTaskReq, PatchTaskReq, SpawnTaskReq,
        TranscriptResp, MessageReq, AnswerAction, AnswerReq, NewTerminalKind,
        CreateTerminalReq, SessionSummary, ProjectsResp, ScrollbackResp, PairStartReq,
        PairStartResp, PairCompleteReq, PairCompleteResp, DeviceView, DevicesResp,
        AgentHookReq, AgentHookResp, AgentToolReq, AgentToolResp, serde_json::Value,
        // Stream
        ClientKind, TermPos, ClientMsg, ServerMsg, PresenceEntry,
    ];
    let mut out = String::from(HEADER);
    for d in decls {
        out.push('\n');
        out.push_str("export ");
        out.push_str(&d);
        out.push('\n');
    }
    out
}

#[test]
fn write_typescript_types() {
    let path = Path::new(env!("CARGO_MANIFEST_DIR")).join("../../web/src/api/types.ts");
    let ts = generate();
    assert_eq!(ts, generate(), "generation is not deterministic");
    std::fs::create_dir_all(path.parent().unwrap()).unwrap();
    if std::fs::read_to_string(&path).ok().as_deref() != Some(ts.as_str()) {
        std::fs::write(&path, ts).unwrap();
    }
}
